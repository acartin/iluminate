begin;

create schema if not exists iluminate;

create table if not exists iluminate.three_d_profiles (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  status text not null default 'draft',
  document_json jsonb not null,
  revision integer not null default 1,
  created_by_user_id bigint references public.auth_users(id) on delete set null,
  updated_by_user_id bigint references public.auth_users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint three_d_profiles_name_ck check (length(btrim(name)) between 1 and 80),
  constraint three_d_profiles_description_ck check (length(description) <= 500),
  constraint three_d_profiles_status_ck check (status in ('draft', 'published', 'archived')),
  constraint three_d_profiles_document_ck check (jsonb_typeof(document_json) = 'object'),
  constraint three_d_profiles_revision_ck check (revision between 1 and 2147483647)
);

create index if not exists three_d_profiles_status_name_idx
  on iluminate.three_d_profiles (status, lower(name));

comment on table iluminate.three_d_profiles is
  'Global fabrication Profile catalog. Records are deliberately cross-tenant and editable only by internal system administrators.';

commit;
