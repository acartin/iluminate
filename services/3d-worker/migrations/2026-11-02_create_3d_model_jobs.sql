begin;

create schema if not exists iluminate;

create unique index if not exists iluminate_projects_id_client_uk
  on iluminate.projects (id, client_id);

create table if not exists iluminate.three_d_model_jobs (
  id bigint generated by default as identity primary key,
  client_id bigint not null references public.auth_clients(id) on delete restrict,
  project_id bigint not null,
  display_name text,
  status text not null default 'queued',
  source_object_key text not null,
  source_checksum text not null,
  source_size_bytes integer not null,
  recipe_json jsonb not null,
  recipe_checksum text not null,
  attempts integer not null default 0,
  available_at timestamptz not null default now(),
  lease_owner text,
  lease_expires_at timestamptz,
  heartbeat_at timestamptz,
  error_code text,
  error_summary text,
  manifest_object_key text,
  manifest_json jsonb,
  created_by_user_id bigint references public.auth_users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz,
  constraint three_d_model_jobs_project_tenant_fk
    foreign key (project_id, client_id) references iluminate.projects (id, client_id) on delete cascade,
  constraint three_d_model_jobs_status_ck
    check (status in ('queued', 'leased', 'processing', 'succeeded', 'failed')),
  constraint three_d_model_jobs_display_name_ck
    check (display_name is null or (display_name = btrim(display_name) and length(display_name) between 1 and 80)),
  constraint three_d_model_jobs_source_key_ck
    check (source_object_key = 'clients/' || client_id || '/3d-models/' || project_id || '/' || id || '/source.svg'),
  constraint three_d_model_jobs_source_checksum_ck
    check (source_checksum ~ '^sha256:[0-9a-f]{64}$'),
  constraint three_d_model_jobs_recipe_checksum_ck
    check (recipe_checksum ~ '^sha256:[0-9a-f]{64}$'),
  constraint three_d_model_jobs_source_size_ck
    check (source_size_bytes between 1 and 2097152),
  constraint three_d_model_jobs_recipe_object_ck
    check (jsonb_typeof(recipe_json) = 'object'),
  constraint three_d_model_jobs_attempts_ck
    check (attempts between 0 and 3),
  constraint three_d_model_jobs_error_code_ck
    check (error_code is null or length(error_code) <= 80),
  constraint three_d_model_jobs_error_summary_ck
    check (error_summary is null or length(error_summary) <= 1000),
  constraint three_d_model_jobs_lease_ck
    check (
      (status in ('leased', 'processing') and lease_owner is not null and lease_expires_at is not null)
      or (status not in ('leased', 'processing') and lease_owner is null and lease_expires_at is null)
    ),
  constraint three_d_model_jobs_manifest_ck
    check (
      (status = 'succeeded' and manifest_object_key is not null and jsonb_typeof(manifest_json) = 'object')
      or (status <> 'succeeded' and manifest_object_key is null and manifest_json is null)
    )
);

create index if not exists three_d_model_jobs_claim_idx
  on iluminate.three_d_model_jobs (available_at, created_at)
  where status in ('queued', 'leased', 'processing') and attempts < 3;

create index if not exists three_d_model_jobs_client_project_idx
  on iluminate.three_d_model_jobs (client_id, project_id, created_at desc);

create table if not exists iluminate.three_d_model_documents (
  project_id bigint primary key,
  client_id bigint not null,
  document_json jsonb not null,
  revision integer not null default 1,
  updated_by_user_id bigint references public.auth_users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint three_d_model_documents_project_tenant_fk
    foreign key (project_id, client_id) references iluminate.projects (id, client_id) on delete cascade,
  constraint three_d_model_documents_json_ck check (jsonb_typeof(document_json) = 'object'),
  constraint three_d_model_documents_revision_ck check (revision between 1 and 2147483647)
);

create index if not exists three_d_model_documents_client_idx
  on iluminate.three_d_model_documents (client_id, updated_at desc);

comment on table iluminate.three_d_model_jobs is
  'Tenant-scoped queue owned exclusively by the isolated SVG-to-solid 3d-worker.';

comment on table iluminate.three_d_model_documents is
  'Independent bounded profile/setup documents for the authenticated 3D Modeler canvas.';

commit;
