begin;

create table if not exists iluminate.viewer_bundles (
  bundle_hash text primary key,
  manifest_bytes bytea not null,
  partitura_bytes bytea not null,
  visual_scene_bytes bytea not null,
  created_at timestamptz not null default now(),
  constraint viewer_bundles_hash_ck check (bundle_hash ~ '^sha256:[0-9a-f]{64}$')
);

create table if not exists iluminate.viewer_links (
  id bigint generated by default as identity primary key,
  client_id bigint not null references public.auth_clients(id) on delete cascade,
  partitura_id bigint not null references iluminate.partituras(id) on delete cascade,
  bundle_hash text not null references iluminate.viewer_bundles(bundle_hash) on delete restrict,
  opaque_slug text not null unique,
  access_policy text not null default 'unlisted',
  expires_at timestamptz,
  revoked_at timestamptz,
  created_by bigint references public.auth_users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint viewer_links_policy_ck check (access_policy in ('review', 'unlisted')),
  constraint viewer_links_expiry_ck check (expires_at is null or expires_at > created_at)
);

create index if not exists viewer_links_tenant_idx on iluminate.viewer_links (client_id, created_at desc);
create index if not exists viewer_links_partitura_idx on iluminate.viewer_links (partitura_id, created_at desc);

commit;
